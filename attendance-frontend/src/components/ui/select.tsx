import * as React from "react"
import * as SelectPrimitive from "@radix-ui/react-select"
import { Check, ChevronDown, ChevronUp } from "lucide-react"
import { cn } from "@/lib/utils"

const Select = SelectPrimitive.Root
const SelectGroup = SelectPrimitive.Group
const SelectValue = SelectPrimitive.Value

const SelectTrigger = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn("flex h-10 w-full items-center justify-between rounded-lg border border-[#E2E8F0] bg-[#FFFFFF] px-3 py-2 text-sm transition-all duration-150 placeholder:text-[#94A3B8] hover:border-[#CBD5E1] focus:outline-none focus:ring-2 focus:ring-[#4F46E5]/20 focus:border-[#4F46E5] disabled:cursor-not-allowed disabled:opacity-50 [&>span]:line-clamp-1 dark:border-[#1E3A5F] dark:bg-[#111827] dark:hover:border-[#334155] dark:focus:border-[#4F46E5]", className)}
    {...props}
  >
    {children}
    <SelectPrimitive.Icon asChild>
      <ChevronDown className="h-4 w-4 text-[#94A3B8]" />
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
))
